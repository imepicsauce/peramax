import { render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { it, expect, vi } from "vitest";
import { PwaControls } from "../src/components/PwaControls";
const pwa = vi.hoisted(() => ({ offline: false, ready: true, installed: true, updateAvailable: true, updating: false, error: "", install: vi.fn(), update: vi.fn() }));
vi.mock("../src/hooks/usePwa", () => ({ usePwa: () => pwa }));
it("offers a portaled update popup, supports Later, and defers during open forms", async () => {
  const user = userEvent.setup();
  const view = render(<PwaControls blocked={false} />);
  const popup = screen.getByRole("region", { name: "App update" });
  expect(view.container.contains(popup)).toBe(false);
  await user.click(within(popup).getByRole("button", { name: "Later" }));
  expect(screen.queryByRole("region", { name: "App update" })).not.toBeInTheDocument();
  expect(pwa.update).not.toHaveBeenCalled();
  await user.click(screen.getByRole("button", { name: "Show update" }));
  view.rerender(<PwaControls blocked={true} />);
  expect(screen.queryByRole("button", { name: "Update now" })).not.toBeInTheDocument();
  expect(screen.getByText("Update ready. Finish your open form first.")).toBeInTheDocument();
  view.rerender(<PwaControls blocked={false} />);
  await user.click(screen.getByRole("button", { name: "Update now" }));
  expect(pwa.update).toHaveBeenCalledTimes(1);
  pwa.updating = true;
  view.rerender(<PwaControls blocked={false} />);
  expect(screen.getByRole("button", { name: "Updating…" })).toBeDisabled();
  pwa.updating = false;
  pwa.updateAvailable = false;
  view.rerender(<PwaControls blocked={false} />);
  expect(screen.queryByRole("region", { name: "App update" })).not.toBeInTheDocument();
});
